def generate_user_message(user_prompt: str) -> str:
    return json.dumps({"userPrompt": user_prompt}, ensure_ascii=False)


def refine_user_message(current_case: dict, instruction: str) -> str:
    return json.dumps(
        {"currentCase": current_case, "userInstruction": instruction}, ensure_ascii=False
    )
